-- Nonclustered indexes for the screens that filter jobs, issues, and receipts.
-- Foreign keys are added only when every child row already has a parent.

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_JOB_DETAILS_JOB_NO' AND object_id = OBJECT_ID('JOB_DETAILS'))
    CREATE INDEX IX_JOB_DETAILS_JOB_NO ON JOB_DETAILS (JOB_NO);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_JOB_DETAILS_INV_NO' AND object_id = OBJECT_ID('JOB_DETAILS'))
    CREATE INDEX IX_JOB_DETAILS_INV_NO ON JOB_DETAILS (INV_NO);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_JOB_DETAILS_CUSTOMER_ID' AND object_id = OBJECT_ID('JOB_DETAILS'))
    CREATE INDEX IX_JOB_DETAILS_CUSTOMER_ID ON JOB_DETAILS (CUSTOMER_ID);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_ISSUED_ITEMS_INV_NO' AND object_id = OBJECT_ID('ISSUED_ITEMS'))
    CREATE INDEX IX_ISSUED_ITEMS_INV_NO ON ISSUED_ITEMS (INV_NO);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_ISSUED_ITEMS_PRO_DATE' AND object_id = OBJECT_ID('ISSUED_ITEMS'))
    CREATE INDEX IX_ISSUED_ITEMS_PRO_DATE ON ISSUED_ITEMS (PRO_DATE);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_ISSUED_ITEMS_JOB_NO' AND object_id = OBJECT_ID('ISSUED_ITEMS'))
    CREATE INDEX IX_ISSUED_ITEMS_JOB_NO ON ISSUED_ITEMS (JOB_NO);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_RECEIVED_ITEMS_INV_NO' AND object_id = OBJECT_ID('RECEIVED_ITEMS'))
    CREATE INDEX IX_RECEIVED_ITEMS_INV_NO ON RECEIVED_ITEMS (INV_NO);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_RECEIVED_ITEMS_PARTNO' AND object_id = OBJECT_ID('RECEIVED_ITEMS'))
    CREATE INDEX IX_RECEIVED_ITEMS_PARTNO ON RECEIVED_ITEMS (PARTNO);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_MASTER_PARTNO' AND object_id = OBJECT_ID('MASTER'))
    CREATE INDEX IX_MASTER_PARTNO ON MASTER (PARTNO);

-- SEQ_NO is unique on the restored customers, but the primary key is NAME.
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_CUSTOMER_INFO_SEQ_NO')
    AND NOT EXISTS (SELECT SEQ_NO FROM CUSTOMER_INFO GROUP BY SEQ_NO HAVING COUNT(*) > 1)
    CREATE UNIQUE INDEX UX_CUSTOMER_INFO_SEQ_NO ON CUSTOMER_INFO (SEQ_NO);

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_JOB_DETAILS_CUSTOMER')
    AND EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_CUSTOMER_INFO_SEQ_NO')
    AND NOT EXISTS (
        SELECT 1 FROM JOB_DETAILS j
        WHERE NOT EXISTS (SELECT 1 FROM CUSTOMER_INFO c WHERE c.SEQ_NO = j.CUSTOMER_ID))
    ALTER TABLE JOB_DETAILS ADD CONSTRAINT FK_JOB_DETAILS_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER_INFO (SEQ_NO);
